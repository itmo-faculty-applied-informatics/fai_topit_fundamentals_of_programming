"""Информационная карточка вычислительного эксперимента

Программа выводит:
-общую длительность всех запусков в секундах;
-общую длительность в минутах;
-комплексный коэффициент;
-квадрат модуля коэффициента по формуле real ** 2 + imag ** 2;
-логическое значение, показывающее, является ли число запусков ненулевым.
"""



name = input('введите имя исследователя: ')
exp = input('введите название эксперимента: ')
count = int(input('введите количество выполненных запусков : '))
time = float(input('введите длительность одного запуска в секундах: '))
real = float(input('введите действительную часть комплексного коэффициента: '))
imag = float(input('введите мнимую часть комплексного коэффициента: '))

stime = time*count
mtime = stime/60
com = complex(real, imag)
kvcom = real **2 + imag**2
has_runs = bool(count)
print('')
print('========================================')
print(f'ЭКСПЕРИМЕНТ: {exp}')
print(f'Исследователь: {name}')
print(f'Запуски: {count:.2f}')
print(f'Общее время: {stime:.2f} c ({mtime:.2f} мин)')
print(f'Коэффициент: {com}')
print(f'Квадрат модуля: {kvcom:.2f}')
print(f'Есть выполненные запуски: {has_runs}')
print('========================================')

print('')
print('ТИПЫ ВВЕДЕННЫХ ДАННЫХ')
print(f'имя исследователя: {type(name)}')
print(f'название эксперимента: {type(exp)}')
print(f'количество выполненных запусков: {type(count)}')
print(f'длительность одного запуска в секундах: {type(time)}')
print(f'действительная часть комплексного коэффициента: {type(real)}')
print(f'мнимая часть комплексного коэффициента: {type(imag)}')
